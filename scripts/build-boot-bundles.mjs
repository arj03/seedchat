// Build the shell's own boot bundles: the offers app (browser/offers-app.js) and the shell
// app (browser/shell-app.js). Unlike an app's `.skb` (scripts/build-app-bundle.mjs), these
// are not something a user drops in — they are loaded at BOOT, alongside the transport
// bundle, so their bytes have to reach the served page rather than sit in the gitignored
// bundle/ directory. This script therefore also generates browser/<name>-bundle.js for
// each, a gitignored module in the shape of seedkernel's host/transport-bundle.ts: the
// blob embedded as base64, so the page's own boot code can import it like any other
// browser/ file.
//
//   node scripts/build-boot-bundles.mjs
//
// Signed under chat-author.key — the SAME author every app build signs under
// (scripts/author.mjs): an author is a key set, not a program, and this demo has exactly
// one. Each app's freshness lineage is its own, though: <name>-author.version tracks that
// app's high-water mark, because the runtime's freshness store keys on (author, app).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { loadCrypto } from "seedkernel-wasm";
import { authorBundle, guestOpFraming } from "seedkernel-wasm/bundle-author";
import { OFFER_PROTO, OFFERS_APP, OFFERS_REQUIRES, offersGuestSource } from "../browser/offers-app.js";
import { SHELL_PROTO, CALL_PROTO, SHELL_APP, SHELL_REQUIRES, shellGuestSource } from "../browser/shell-app.js";
import { authorKeys, nextVersion, saveVersion } from "./author.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

const toHex = (b) => Buffer.from(b).toString("hex");

/** What stands in front of each guest: seedkernel's op-frame, then the network library
 *  every guest that reaches `_net` shares (assembly/guest-lib/net.js). LF, because these
 *  bytes are signed and a checkout's line endings are the machine's. */
const prelude = guestOpFraming()
  + readFileSync(join(root, "assembly", "guest-lib", "net.js"), "utf8").replace(/\r\n/g, "\n");

/** Each boot bundle: a guest-only bundle, its claims and a reach. `name` names the files;
 *  `constant` the generated module's exports. */
const BUNDLES = [
  { name: "offers", constant: "OFFERS", app: OFFERS_APP, protocols: [OFFER_PROTO],
    guestSource: offersGuestSource(prelude), guestRequires: OFFERS_REQUIRES },
  { name: "shell", constant: "SHELL", app: SHELL_APP, protocols: [SHELL_PROTO, CALL_PROTO],
    guestSource: shellGuestSource(prelude), guestRequires: SHELL_REQUIRES },
];

const sodium = await loadCrypto();

const keys = authorKeys(sodium);

for (const b of BUNDLES) {
  const { blob, manifest, author } = authorBundle(sodium, keys, {
    app: b.app,
    // Freshness: this app's OWN high-water mark, beside the key under its own file.
    version: nextVersion(b.app),
    protocols: b.protocols,
    // Guest-only: neither app does a transform of its own.
    modules: [],
    guestSource: b.guestSource,
    guestRequires: b.guestRequires,
  });
  saveVersion(b.app, manifest.version);

  const skbOutPath = join(root, "bundle", `${b.name}.skb`);
  mkdirSync(dirname(skbOutPath), { recursive: true });
  writeFileSync(skbOutPath, blob);

  const js = `// GENERATED by scripts/build-boot-bundles.mjs — DO NOT EDIT.
// The ${b.name} app's own boot bundle (browser/${b.name}-app.js), loaded at boot exactly
// like seedkernel's transport bundle, signed by
//   ${toHex(author)}
// under the hybrid suite 0x02 (Ed25519 + ML-DSA-65) with chat-author.key, the same
// author every app bundle signs under. Its own freshness lineage lives in
// ${b.name}-author.version: the runtime's freshness store keys on (author, app).
//
// The page is served from browser/ (bundle/ is not), so this embedded module is how the
// boot bundle reaches the tab — the shape of seedkernel's host/transport-bundle.ts.
const B64 = "${Buffer.from(blob).toString("base64")}";
let decoded = null;
/** The boot bundle as raw bytes. A fresh copy per call. */
export function ${b.name}BundleBytes() {
  if (decoded === null) {
    const bin = atob(B64);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    decoded = out;
  }
  return decoded.slice();
}
/** The author this bundle is signed by (hex) — what \`admit\` pins the boot load to
 *  (shell.js), read off the artifact rather than restated by hand. */
export const ${b.constant}_AUTHOR_HEX = "${toHex(author)}";
/** The app name this bundle's manifest declares — what \`admit\` checks beside the author. */
export const ${b.constant}_APP = ${JSON.stringify(manifest.app)};
`;
  writeFileSync(join(root, "browser", `${b.name}-bundle.js`), js);
  console.log(`  wrote bundle/${b.name}.skb (app ${manifest.app} v${manifest.version}) and browser/${b.name}-bundle.js`);
}
